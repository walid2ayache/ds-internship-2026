r"""Etape 7: build one combined results table -> results/RESULTS.md.
Run from the repo root:  .venv\Scripts\python.exe scripts\07_report.py

Reads the four metrics JSONs only: it trains nothing and edits no other script.
Selection is by VALIDATION only; test numbers are reporting only.

XGBoost caveat: 03_baseline.py stores VAL F1 at the chosen threshold, not VAL
PR-AUC, so that family is selected by VAL F1 (the rule the script itself used).
The report says so explicitly instead of hiding it.
"""
import json
import statistics
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
FAMILIES = ["XGBoost (no graph)", "GNN (main)", "Ablation", "Imbalance"]
N_ROWS = {"XGBoost (no graph)": 4, "GNN (main)": 6, "Ablation": 8, "Imbalance": 8}
SEEDS = {"XGBoost (no graph)": "1 run", "GNN (main)": "3 seeds",
         "Ablation": "3 seeds", "Imbalance": "5 seeds"}
IMB_LOSS = {"plain": "plain", "weighted": "class weights",
            "sqrt_weighted": "sqrt weights", "focal_g2": "focal γ=2"}


def load(name):
    with open(RESULTS / name, encoding="utf-8") as f:
        return json.load(f)


def mean_std(runs, key):
    """(mean, population std); (value, None) for a single run; None if absent."""
    vals = [float(r[key]) for r in runs if r.get(key) is not None]
    if not vals:
        return None
    if len(vals) == 1:
        return vals[0], None
    return statistics.mean(vals), statistics.pstdev(vals)


def add_row(rows, family, label, feats, loss, runs, val_pr_key="val_pr_auc",
            val_f1_key=None):
    row = {"family": family, "label": label, "feats": feats, "loss": loss,
           "n": len(runs), "val_pr": None, "val_f1": None}
    if val_pr_key:
        row["val_pr"] = mean_std(runs, val_pr_key)
    if val_f1_key:
        row["val_f1"] = statistics.mean([r[val_f1_key] for r in runs])
    for k in ("pr_auc", "f1", "precision", "recall", "f1_steps_35_42"):
        row[k] = mean_std(runs, k)
    rows.append(row)


def val_score(row):
    return row["val_pr"][0] if row["val_pr"] else row["val_f1"]


def desc(row):
    return f"{row['label']} · {row['feats']} · {row['loss']}"


def fmt(pair):
    if pair is None:
        return "—"
    m, s = pair
    return f"{m:.3f}" if s is None else f"{m:.3f} ± {s:.3f}"


def check_summary(data):
    """Cross-check recomputed means against the summary stored by each script."""
    for name, runs in data["runs"].items():
        for k, stored in data["summary"][name].items():
            mean = statistics.mean(r[k] for r in runs)
            ref = stored[0] if isinstance(stored, list) else stored
            assert abs(mean - ref) < 1e-9, (name, k, mean, ref)


def build_rows():
    rows = []
    for key, r in load("baseline_metrics.json").items():
        add_row(rows, FAMILIES[0], "XGBoost",
                "local" if "local" in key else "all",
                "class weights" if key.endswith("weighted") else "plain",
                [r], val_pr_key=None, val_f1_key="val_f1_at_thr")
    for key, runs in load("gnn_metrics.json")["runs"].items():
        kind, loss = key.split("_")
        add_row(rows, FAMILIES[1], kind.upper(), "all",
                "class weights" if loss == "weighted" else "plain", runs)
    for key, runs in load("gnn_ablation.json")["runs"].items():
        kind, feats, drop = key.split("|")
        add_row(rows, FAMILIES[2], f"{kind.upper()} (in-drop {drop.split('=')[1]})",
                feats, "plain", runs)
    for key, runs in load("imbalance_metrics.json")["runs"].items():
        _, feats, loss = key.split("|")
        add_row(rows, FAMILIES[3], "SAGE", feats, IMB_LOSS[loss], runs)
    return rows


def main():
    for name in ("gnn_metrics.json", "gnn_ablation.json", "imbalance_metrics.json"):
        check_summary(load(name))

    rows = build_rows()
    assert len(rows) == 26, len(rows)
    for fam, n in N_ROWS.items():
        assert sum(r["family"] == fam for r in rows) == n, fam

    winners = {fam: max((r for r in rows if r["family"] == fam), key=val_score)
               for fam in FAMILIES}
    ordered = []
    for fam in FAMILIES:
        ordered += sorted((r for r in rows if r["family"] == fam),
                          key=val_score, reverse=True)

    lines = [
        "# Results: Elliptic Bitcoin fraud detection",
        "",
        f"Generated by `scripts/07_report.py` on {datetime.now():%Y-%m-%d %H:%M} "
        "from `results/baseline_metrics.json`, `gnn_metrics.json`, "
        "`gnn_ablation.json` and `imbalance_metrics.json`.",
        "",
        "Time split: train steps 1–29 / val 30–34 / test 35–49. Unknown-label "
        "nodes are excluded from loss and metrics but stay in the graph. All "
        "numbers are illicit-class metrics on labeled test nodes (steps 35–49); "
        "the decision threshold maximises illicit F1 on VAL and is then applied "
        "unchanged to test. Test illicit rate is 6.5% vs 16.8% on val "
        "(distribution shift).",
        "",
        "## All configs tried",
        "",
        "Sorted within each family by validation score (**★** = family pick; "
        "XGBoost is scored by VAL F1, see note 4); test columns are reporting "
        "only and never influenced a selection. "
        "Cells are mean ± std over seeds; XGBoost has one run per config, so no "
        "std. `—` = not recorded by that script.",
        "",
        "| # | Family | Config | Features | Loss / imbalance | VAL PR-AUC | "
        "Test PR-AUC | Test F1 | Precision | Recall | F1 steps 35–42 |",
        "|---:|---|---|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for i, r in enumerate(ordered, 1):
        star = " ★" if r is winners[r["family"]] else ""
        lines.append(
            f"| {i} | {r['family']} | {r['label']}{star} | {r['feats']} | "
            f"{r['loss']} | {fmt(r['val_pr'])} | {fmt(r['pr_auc'])} | "
            f"{fmt(r['f1'])} | {fmt(r['precision'])} | {fmt(r['recall'])} | "
            f"{fmt(r['f1_steps_35_42'])} |")

    lines += [
        "",
        "Table notes: XGBoost rows show `—` under VAL PR-AUC because "
        "`03_baseline.py` records VAL F1 at the chosen threshold only, never "
        "VAL PR-AUC. The six GNN (main) rows show `—` under F1 steps 35–42 "
        "because `04_gnn.py` stored per-step F1, not the pooled number.",
        "",
        "## Family picks by VALIDATION only",
        "",
        "Rule: maximum mean validation score per family. XGBoost is the one "
        "exception: its JSON has no VAL PR-AUC, so it is selected by VAL F1, "
        "which is what `03_baseline.py` itself did. `Test *` columns are shown "
        "for reference and were not used to pick anything.",
        "",
        "| Family | Runs | Selected config | Rule | VAL score | "
        "Runner-up (Δ VAL) | Test PR-AUC* | Test F1* |",
        "|---|---|---|---|---:|---|---:|---:|",
    ]
    for fam in FAMILIES:
        fam_rows = sorted((r for r in rows if r["family"] == fam),
                          key=val_score, reverse=True)
        w, ru = fam_rows[0], fam_rows[1]
        rule = ("VAL F1 (no val PR-AUC logged)" if fam == FAMILIES[0]
                else "VAL PR-AUC")
        lines.append(
            f"| {fam} | {SEEDS[fam]} | {desc(w)} | {rule} | "
            f"{val_score(w):.3f} | {desc(ru)} "
            f"({val_score(w) - val_score(ru):+.4f}) | "
            f"{fmt(w['pr_auc'])} | {fmt(w['f1'])} |")

    gnn_rows = sorted((r for r in rows if r["family"] != FAMILIES[0]),
                      key=val_score, reverse=True)
    top = gnn_rows[0]
    spread = val_score(top) - val_score(gnn_rows[2])
    lines += [
        "",
        f"Across the three GNN families the highest VAL PR-AUC is {desc(top)} "
        f"({val_score(top):.3f}, {top['family']}); next are "
        f"{desc(gnn_rows[1])} ({val_score(gnn_rows[1]):.3f}, "
        f"{gnn_rows[1]['family']}) and {desc(gnn_rows[2])} "
        f"({val_score(gnn_rows[2]):.3f}, {gnn_rows[2]['family']}).",
    ]
    if all(r["label"].startswith("SAGE") and r["feats"] == "all"
           and r["loss"] == "plain" for r in gnn_rows[:3]):
        lines.append(
            f"Those three are the same configuration (SAGE, all features, plain "
            f"loss, in-drop 0.5) run by three different scripts, so the "
            f"{spread:.4f} spread is seed noise, not three independent wins.")

    sage_stds = [r["val_pr"][1] for r in rows
                 if r["val_pr"] and r["label"].startswith("SAGE")]
    best_test = max(rows, key=lambda r: r["pr_auc"][0])
    local_sage = [r for r in rows if r["label"].startswith("SAGE")
                  and r["feats"] == "local"]
    best_local = max(local_sage, key=lambda r: r["pr_auc"][0])
    lines += [
        "",
        "## Limitations and honesty notes",
        "",
        f"1. **VAL is saturated.** SAGE reaches VAL PR-AUC ≈0.95 with seed std "
        f"up to {max(sage_stds):.3f}, and the top three configs differ by "
        f"{spread:.4f}. VAL cannot reliably rank these models; the family "
        "picks are the mechanical application of the rule, not evidence that "
        "the picked config is better.",
        "2. **Threshold rule.** The threshold maximises illicit F1 on VAL "
        "(grid 0.05–0.95) and is reused unchanged on test, for every model.",
        "3. **Seeds.** Mean ± population std (ddof=0) over 3 seeds for GNN "
        "(main) and ablation, 5 for imbalance, and a single run for XGBoost.",
        "4. **XGBoost selection metric differs.** `03_baseline.py` never "
        "logged VAL PR-AUC, so its family pick uses VAL F1. Aligning it with "
        "the other families would require editing and re-running that script; "
        "that was not done here.",
        "5. **Repeated configs are not independent.** SAGE + all features + "
        "plain loss appears in all three GNN families; main and ablation even "
        "use the same seeds 0–2, so those rows are near-duplicates rather than "
        "independent evidence.",
        "6. **Temporal collapse.** All models fall to near-zero F1 on steps "
        "43–49. The pooled F1 for steps 35–42 is reported where the script "
        "saved it; the main GNN rows only have per-step values.",
        f"7. **VAL and test disagree.** The val-selected {desc(top)} tests at "
        f"PR-AUC {top['pr_auc'][0]:.3f}, while local-feature SAGE tests at up "
        f"to {best_local['pr_auc'][0]:.3f} ({desc(best_local)}) with a lower "
        f"VAL PR-AUC ({val_score(best_local):.3f}). The single highest test "
        f"PR-AUC is {desc(best_test)} ({best_test['pr_auc'][0]:.3f}), which is "
        "not a family pick either. Per the rules the val picks stand; the "
        "README must not call the val-selected GNN the best test model.",
        "",
    ]

    text = "\n".join(lines)
    (RESULTS / "RESULTS.md").write_text(text, encoding="utf-8")
    print(f"rows: {len(rows)}")
    print(f"Wrote {RESULTS / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
